"""MT-6.3-01 — SSE fan-out: web-shaped streams under agent-simulation load.

Section 18's "SSE fan-out" element: concurrent SSE connections receiving
the event load generated by the agent simulation, measuring
publish-to-receipt latency per NFR-03 — extending MT-1.10-06's method
(same percentile math, same publish-point discipline) to the fan-out
count this scenario implies.

Connection set (documented rationale): **1 global** owner stream
(dashboard-style, no project filter) + **one per seeded project (10)**
(board views) = 11 connections — the shape the web client opens
(use-event-stream: project filter for board/review views, unfiltered for
the dashboard; MT-4.11-04 owns the browser side).

Timing method (stated precisely for MT-6.3-02's report):

* The publish instant is server-side and post-commit inside the
  checkpoint request, so from this client process it lies in
  ``[t_send, t_resp]``. Each delivery records **both** bounds against the
  frame receipt:
  ``upper = t_receipt - t_send`` (conservative superset) and
  ``lower = max(0, t_receipt - t_resp)`` (delivery-only floor).
* NFR-03 is judged on the **upper** bound: if its p95 < 2 s, the true
  publish->receipt p95 < 2 s wherever publish sat inside the window.
* ``occurred_at`` in the envelope is second-precision — too coarse for a
  2 s budget — recorded as traffic, never used for timing.
* Correlation key: the checkpoint POST response's ``checkpoint.id`` vs
  the frame's ``data.checkpoint_id`` (exact match, per MT-1.10-06's
  publish-point discipline).

Run: ``python e2e/perf/sse_fanout.py --run-id 1``.
Execution instructions: ``docs/plan/perf-runbook.md``.
"""

from __future__ import annotations

import argparse
import os
import sys
import threading
import time
from typing import Any

from agent_simulation import build_payload, start_simulation
from perf_common import (
    STREAM_PATH,
    Api,
    PerfError,
    SseConnection,
    judge,
    load_manifest,
    load_thresholds,
    summarize,
    verdict_line,
    write_results,
)
from seed_perf_fixture import DEFAULT_OWNER_PASSWORD

DEFAULT_OWNER_USERNAME = "perf-owner"


class CorrelationRegistry:
    """Matches checkpoint requests to their SSE receipts, either arrival order.

    A frame can beat the HTTP response (publish runs inside the request),
    so receipts arriving early park in ``_receipts`` and are claimed when
    the response finishes the entry — all under one lock, so no
    check-then-set race can drop a receipt.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._inflight = 0
        self._pending: dict[str, dict[str, Any]] = {}
        self._receipts: dict[str, float] = {}
        self._done: set[str] = set()
        self.completed: list[dict[str, Any]] = []

    def begin(self, agent_index: int) -> dict[str, Any]:
        with self._lock:
            self._inflight += 1
        return {"agent": agent_index}

    def finish(
        self,
        agent_index: int,
        handle: dict[str, Any],
        checkpoint_id: str,
        t_send: float,
        t_resp: float,
    ) -> None:
        with self._lock:
            self._inflight -= 1
            receipt = self._receipts.pop(checkpoint_id, None)
            entry: dict[str, Any] = {
                "checkpoint_id": checkpoint_id,
                "agent": agent_index,
                "t_send": t_send,
                "t_resp": t_resp,
                "t_receipt": receipt,
            }
            self._pending[checkpoint_id] = entry
            if receipt is not None:
                self._finalize(checkpoint_id)

    def on_frame(self, checkpoint_id: str, t_receipt: float) -> None:
        with self._lock:
            if checkpoint_id in self._done:
                return  # a second connection delivered the same event (fan-out)
            if checkpoint_id in self._pending:
                self._pending[checkpoint_id]["t_receipt"] = t_receipt
                self._finalize(checkpoint_id)
            else:
                self._receipts[checkpoint_id] = t_receipt

    def _finalize(self, checkpoint_id: str) -> None:
        entry = self._pending.pop(checkpoint_id)
        if entry["t_receipt"] is None:
            self._pending[checkpoint_id] = entry  # not complete yet
            return
        self._done.add(checkpoint_id)
        upper = (entry["t_receipt"] - entry["t_send"]) * 1000.0
        lower = max(0.0, (entry["t_receipt"] - entry["t_resp"]) * 1000.0)
        self.completed.append(
            {
                "checkpoint_id": checkpoint_id,
                "agent": entry["agent"],
                "upper_ms": round(upper, 2),
                "lower_ms": round(lower, 2),
            }
        )

    def drain(self) -> list[dict[str, Any]]:
        with self._lock:
            return list(self.completed)

    def outstanding(self) -> int:
        """Checkpoint responses still waiting for their delivery receipt."""
        with self._lock:
            return self._inflight + len(self._pending)


class StreamStats:
    """Per-connection frame counters plus faults (never silently retried)."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self.per_connection: dict[str, dict[str, int]] = {}
        self.faults: list[str] = []
        self._correlated = 0

    def event(self, label: str) -> None:
        with self._lock:
            row = self.per_connection.setdefault(label, {"events": 0, "heartbeats": 0})
            row["events"] += 1

    def heartbeat(self, label: str) -> None:
        with self._lock:
            row = self.per_connection.setdefault(label, {"events": 0, "heartbeats": 0})
            row["heartbeats"] += 1

    def fault(self, label: str, detail: str) -> None:
        with self._lock:
            self.faults.append(f"{label}: {detail}")

    def correlated(self) -> None:
        """One frame carrying a checkpoint_id arrived (fan-out multiplicity)."""
        with self._lock:
            self._correlated += 1

    @property
    def correlated_total(self) -> int:
        with self._lock:
            return self._correlated


def reader_loop(
    conn: SseConnection,
    label: str,
    registry: CorrelationRegistry,
    stats: StreamStats,
    shutdown: threading.Event,
) -> None:
    """Read frames until shutdown/close; correlate checkpoint receipts."""
    while not shutdown.is_set():
        try:
            kind, envelope = conn.read_frame()
        except Exception as exc:  # noqa: BLE001 — close() unblocks reads on purpose
            if shutdown.is_set():
                break  # expected: main closed the socket to wake us
            stats.fault(label, repr(exc))
            break
        if kind == "heartbeat":
            stats.heartbeat(label)
            continue
        stats.event(label)
        data = envelope.get("data") if isinstance(envelope.get("data"), dict) else {}
        checkpoint_id = data.get("checkpoint_id") if isinstance(data, dict) else None
        if checkpoint_id:
            stats.correlated()
            registry.on_frame(str(checkpoint_id), time.perf_counter())
    try:
        conn.close()
    except Exception:  # noqa: BLE001 — main may have closed it already
        pass


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    thresholds = load_thresholds()
    parser = argparse.ArgumentParser(
        description="WP-6.3 SSE fan-out — publish->receipt under agent load (MT-6.3-01)."
    )
    parser.add_argument("--run-id", type=int, default=1)
    parser.add_argument("--duration", type=float, default=120.0, help="seconds of load")
    parser.add_argument("--agents", type=int, default=thresholds["scenario"]["agents"])
    parser.add_argument(
        "--checkpoint-interval",
        type=float,
        default=float(thresholds["scenario"]["checkpoint_interval_s"]),
    )
    parser.add_argument("--checkpoints-per-task", type=int, default=3)
    parser.add_argument("--manifest", default=None, help="path to the seed manifest")
    parser.add_argument("--global-connections", type=int, default=1)
    parser.add_argument("--project-connections", type=int, default=10)
    parser.add_argument(
        "--grace",
        type=float,
        default=10.0,
        help="seconds readers keep consuming after load stops (trailing receipts)",
    )
    parser.add_argument("--owner-username", default=None)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    manifest = load_manifest(args.manifest)
    thresholds = load_thresholds()
    budget_ms = thresholds["nfr03"]["event_delivery_p95_ms"]

    owner_api = Api()
    owner_api.login(
        args.owner_username or manifest["owner"]["username"],
        os.environ.get("PERF_OWNER_PASSWORD", DEFAULT_OWNER_PASSWORD),
    )

    # Connection set: 1 global + one per project (web-shaped filters).
    paths: list[tuple[str, str]] = [("global", STREAM_PATH)]
    for pid in manifest["projects"][: args.project_connections]:
        paths.append((f"project:{pid}", f"{STREAM_PATH}?project={pid}"))

    connections: list[tuple[str, SseConnection]] = []
    for label, path in paths:
        connections.append((label, SseConnection(owner_api, path)))

    registry = CorrelationRegistry()
    stats = StreamStats()
    reader_shutdown = threading.Event()
    readers = [
        threading.Thread(
            target=reader_loop,
            args=(conn, label, registry, stats, reader_shutdown),
            name=f"sse-{label}",
            daemon=True,
        )
        for label, conn in connections
    ]
    for reader in readers:
        reader.start()

    # The agent simulation IS the event load (Section 18 wording): start it,
    # join every worker, and only then build the payload (building earlier
    # would snapshot empty counts — payload must outlive the join).
    stop_event = threading.Event()
    start_event = threading.Event()
    deadline_at = time.perf_counter() + args.duration
    sim_manifest, sim_thresholds, sink, workers = start_simulation(
        args,
        registry=registry,
        stop_event=stop_event,
        start_event=start_event,
        deadline_at=deadline_at,
    )
    for worker in workers:
        worker.join(timeout=max(0.0, deadline_at - time.perf_counter()) + 120.0)
    payload = build_payload(args, sim_manifest, sim_thresholds, sink, workers)

    # Trailing receipts: keep the readers alive past the last publish.
    time.sleep(args.grace)
    reader_shutdown.set()
    for label, conn in connections:
        conn.close()  # unblock readers parked in readline
    for reader in readers:
        reader.join(timeout=10.0)

    completed = registry.drain()
    upper = sorted(entry["upper_ms"] for entry in completed)
    lower = sorted(entry["lower_ms"] for entry in completed)
    missing = registry.outstanding()
    upper_stats = summarize(upper)
    verdict = judge(upper_stats["p95_ms"], budget_ms)
    verdict["missing_deliveries"] = missing
    verdict["pass"] = bool(verdict["pass"] and missing == 0)

    checkpoints_ok = payload["counts"]["checkpoint_ok"]
    deliveries = len(upper)
    distinct_checkpoints = deliveries + missing
    fanout_report = {
        "connections_opened": len(connections),
        "connection_set": [label for label, _ in connections],
        "per_connection": stats.per_connection,
        "stream_faults": stats.faults,
        "checkpoint_responses": checkpoints_ok,
        "deliveries_timed": deliveries,
        "missing_deliveries": missing,
        "correlated_frames": stats.correlated_total,
        "avg_deliveries_per_checkpoint": (
            round(stats.correlated_total / distinct_checkpoints, 2)
            if distinct_checkpoints
            else None
        ),
    }
    result: dict[str, Any] = {
        "run_id": args.run_id,
        "duration_s": args.duration,
        "grace_s": args.grace,
        "method": (
            "publish->receipt upper bound = frame receipt - request send "
            "(publish is post-commit inside the checkpoint request, so the "
            "true publish instant lies in [t_send, t_resp]); lower bound = "
            "receipt - response as the delivery-only floor; NFR-03 judged "
            "on the upper bound; MT-1.10-06 percentile method"
        ),
        "fanout": fanout_report,
        "latency_ms": {
            "publish_to_receipt_upper": upper_stats,
            "delivery_lower_bound": summarize(lower),
        },
        "verdicts": {"nfr03_event_delivery_p95": verdict},
        "thresholds_source": "e2e/perf/thresholds.json (plan-derived, Section 5.2)",
        "agent_load": payload,
    }
    path = write_results(f"sse_fanout_run{args.run_id}", result)
    print(
        f"sse_fanout run={args.run_id} duration={args.duration}s "
        f"connections={len(connections)} deliveries={deliveries} "
        f"missing={missing} faults={len(stats.faults)} "
        f"claims_ok={payload['counts']['claim_ok']} "
        f"checkpoints_ok={checkpoints_ok}"
    )
    print(verdict_line("nfr03_event_delivery_p95 (upper bound)", verdict))
    print(f"results: {path}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except PerfError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(2)
