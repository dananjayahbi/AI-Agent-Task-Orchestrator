"""Deterministic builder for the WP-1.12 test fixtures and sample corpus.

Run from the repository root (documented regeneration command):

    uv run --directory backend python tests/attachments/fixtures/build_fixtures.py

**Provenance / licensing** (Section 20.4 item 3, MT-1.12-08 risk note):
every file here is generated by this script from synthetic strings drawn
in this repository — no third-party content, and no font files are
committed (the raster uses a system/Pillow font at generation time
only; the committed output is a simple render of our own text). Tests
depend on the committed files' *text properties*, never on the
generator: OCR assertions are substring-based (MT-1.12-08 risk note:
prove OCR ran without being engine-fragile).

Products — ``fixtures/corpus/`` holds the Section 19 sample set plus
the large PDF (exactly what MT-1.12-08's acceptance names); the mixed
PDF is a sibling fixture for MT-1.12-03's unit tests:

===================  ==================================================
``corpus/screenshot.png``  Section 19 sample set: a rendered "screenshot"
``corpus/text.pdf``        text-layer PDF (OCR must NOT run)
``corpus/scanned.pdf``     image-only PDF (OCR fallback must run)
``corpus/large.pdf``       12 numbered pages (page-numbering acceptance)
``corpus/sample.docx``     heading + list + table (MT-1.12-04)
``corpus/sample.md``       Markdown, LF endings (MT-1.12-04)
``mixed.pdf``              page 1 text, page 2 image-only (MT-1.12-03)
===================  ==================================================
"""

from __future__ import annotations

import io
import zipfile
import zlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from pypdf import PdfWriter
from pypdf.generic import (
    DecodedStreamObject,
    DictionaryObject,
    NameObject,
    NumberObject,
    StreamObject,
)

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "corpus"

# The strings OCR must recover (tests assert these substrings, never
# full transcripts — MT-1.12-08 risk note: engine-fragile exact match).
SCREENSHOT_TEXT = "Orchestrator screenshot: form saved successfully"
SCANNED_TEXT = "Scanned page: hello orchestrator pipeline"
MIXED_TEXT_PAGE = "Mixed page one: plain text layer, no OCR needed."
MIXED_IMAGE_PAGE = "Mixed page two: image only, OCR fallback."
PAGE_LABELS = [f"Text page number {index} of 12" for index in range(1, 13)]

LETTER_W, LETTER_H = 612, 792


def _font(size: int) -> ImageFont.ImageFont | ImageFont.FreeTypeFont:
    """A legible font for rendering, without committing any font file."""
    for candidate in ("arial.ttf", "DejaVuSans.ttf", "arialbd.ttf"):
        try:
            return ImageFont.truetype(candidate, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def _render(lines: list[str], *, size: tuple[int, int] = (1224, 1584)) -> Image.Image:
    """Render *lines* as a clean white page image (a screenshot-ish sheet)."""
    image = Image.new("RGB", size, "white")
    draw = ImageDraw.Draw(image)
    font = _font(52)
    y = 120
    for line in lines:
        draw.text((80, y), line, font=font, fill="black")
        y += 90
    return image


def _png(image: Image.Image) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


# --- PDF construction (pypdf writer; validated by re-reading) ----------------


def _add_text_page(writer: PdfWriter, lines: list[str]) -> None:
    """Append a Helvetica text-layer page (extractable, no images)."""
    page = writer.add_blank_page(width=LETTER_W, height=LETTER_H)
    commands = ["BT", "/F1 16 Tf", "24 TL", "72 720 Td"]
    for line in lines:
        escaped = line.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
        commands.append(f"({escaped}) Tj T*")
    commands.append("ET")
    stream = DecodedStreamObject()
    stream.set_data("\n".join(commands).encode("ascii"))
    page[NameObject("/Contents")] = writer._add_object(stream)
    page[NameObject("/Resources")] = DictionaryObject(
        {
            NameObject("/Font"): DictionaryObject(
                {
                    NameObject("/F1"): DictionaryObject(
                        {
                            NameObject("/Type"): NameObject("/Font"),
                            NameObject("/Subtype"): NameObject("/Type1"),
                            NameObject("/BaseFont"): NameObject("/Helvetica"),
                        }
                    )
                }
            )
        }
    )


def _add_image_page(writer: PdfWriter, lines: list[str]) -> None:
    """Append an image-only page — no text layer at all (a "scan")."""
    page = writer.add_blank_page(width=LETTER_W, height=LETTER_H)
    rendered = _render(lines)
    image_stream = StreamObject()
    image_stream[NameObject("/Type")] = NameObject("/XObject")
    image_stream[NameObject("/Subtype")] = NameObject("/Image")
    image_stream[NameObject("/Width")] = NumberObject(rendered.width)
    image_stream[NameObject("/Height")] = NumberObject(rendered.height)
    image_stream[NameObject("/ColorSpace")] = NameObject("/DeviceRGB")
    image_stream[NameObject("/BitsPerComponent")] = NumberObject(8)
    image_stream[NameObject("/Filter")] = NameObject("/FlateDecode")
    image_stream.set_data(zlib.compress(rendered.convert("RGB").tobytes()))
    image_ref = writer._add_object(image_stream)

    content = DecodedStreamObject()
    content.set_data(f"q {LETTER_W} 0 0 {LETTER_H} 0 0 cm /Im0 Do Q".encode("ascii"))
    page[NameObject("/Contents")] = writer._add_object(content)
    page[NameObject("/Resources")] = DictionaryObject(
        {NameObject("/XObject"): DictionaryObject({NameObject("/Im0"): image_ref})}
    )


def _pdf_ordered(pages: list[tuple[str, list[str]]]) -> bytes:
    """One PDF whose pages follow the exact (kind, lines) order given."""
    writer = PdfWriter()
    for kind, lines in pages:
        if kind == "text":
            _add_text_page(writer, lines)
        else:
            _add_image_page(writer, lines)
    buffer = io.BytesIO()
    writer.write(buffer)
    return buffer.getvalue()


# --- DOCX construction (minimal OPC package, real word/document.xml) ---------

_W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"


def _docx_paragraph(text: str, *, style: str | None = None, bullet: bool = False) -> str:
    props = ""
    if style:
        props += f'<w:pStyle w:val="{style}"/>'
    if bullet:
        props += '<w:numPr><w:ilvl w:val="0"/><w:numId w:val="1"/></w:numPr>'
    ppr = f"<w:pPr>{props}</w:pPr>" if props else ""
    return f'<w:p>{ppr}<w:r><w:t xml:space="preserve">{text}</w:t></w:r></w:p>'


def _docx_bytes() -> bytes:
    """Heading, paragraph, bullet list and a 2x2 table, in document order."""
    table = (
        "<w:tbl><w:tr>"
        "<w:tc><w:p><w:r><w:t>Key</w:t></w:r></w:p></w:tc>"
        "<w:tc><w:p><w:r><w:t>Value</w:t></w:r></w:p></w:tc>"
        "</w:tr><w:tr>"
        "<w:tc><w:p><w:r><w:t>Owner</w:t></w:r></w:p></w:tc>"
        "<w:tc><w:p><w:r><w:t>QA</w:t></w:r></w:p></w:tc>"
        "</w:tr></w:tbl>"
    )
    body = "".join(
        [
            _docx_paragraph("Project Alpha Plan", style="Heading1"),
            _docx_paragraph("This DOCX carries structure for extraction."),
            _docx_paragraph("First deliverable", bullet=True),
            _docx_paragraph("Second deliverable", bullet=True),
            table,
            "<w:sectPr/>",
        ]
    )
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        f'<w:document xmlns:w="{_W_NS}"><w:body>{body}</w:body></w:document>'
    )
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType='
        '"application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" ContentType='
        '"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
        "</Types>"
    )
    rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type='
        '"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
        'Target="word/document.xml"/></Relationships>'
    )
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", content_types)
        archive.writestr("_rels/.rels", rels)
        archive.writestr("word/document.xml", document)
    return buffer.getvalue()


MARKDOWN_SAMPLE = (
    "# Sample Notes\n\n"
    "First paragraph with **bold** emphasis and a [link](https://example.invalid).\n\n"
    "- item one\n"
    "- item two\n\n"
    "Closing paragraph for the corpus.\n"
)


def build() -> list[Path]:
    """(Re)generate every fixture; return the files written."""
    CORPUS.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    def emit(name: str, data: bytes) -> None:
        path = CORPUS / name
        path.write_bytes(data)
        written.append(path)

    emit(
        "screenshot.png",
        _png(
            _render(
                [
                    SCREENSHOT_TEXT,
                    "Task PID00007-T004 moved to in progress",
                    "Two attachments uploaded without errors",
                ]
            )
        ),
    )
    emit("text.pdf", _pdf_ordered([("text", [PAGE_LABELS[0], "Hello from the text layer."])]))
    emit("scanned.pdf", _pdf_ordered([("image", [SCANNED_TEXT])]))
    # The mixed PDF is an MT-1.12-03 unit fixture, not a corpus member
    # (the Section 19 sample set is exactly five files plus large.pdf).
    (HERE / "mixed.pdf").write_bytes(
        _pdf_ordered(
            [
                ("text", [MIXED_TEXT_PAGE]),
                ("image", [MIXED_IMAGE_PAGE]),
            ]
        )
    )
    emit(
        "large.pdf",
        _pdf_ordered([("text", [label, "Body line for the page."]) for label in PAGE_LABELS]),
    )
    emit("sample.docx", _docx_bytes())
    emit("sample.md", MARKDOWN_SAMPLE.encode("utf-8"))
    return written


if __name__ == "__main__":
    for output in build():
        print(f"wrote {output} ({output.stat().st_size} bytes)")
